import type { Direction, MetricFormat, ServiceId } from "../domain/types";

/**
 * KPI definitions — deliberately 5–7 per service, not thirty.
 *
 * `metricKey` resolves against the derived metric context the engine builds
 * for each entity/service, so a KPI's `actual` is always the same number the
 * Overview tab shows. Targets are contractual and do not vary by entity.
 *
 * Each tower's KPI set covers its named sub-services: F&A spans AP, AR,
 * Travel, R2R and Treasury; HR Ops spans TA, Payroll and L&D; and so on.
 */
export interface KpiSpec {
  id: string;
  serviceId: ServiceId;
  name: string;
  description: string;
  metricKey: string;
  target: number;
  direction: Direction;
  unit: MetricFormat;
  /** Tolerance past target that still counts as amber, as % of target. */
  amberBandPct: number;
  /** Month-to-month noise amplitude, as a fraction of the value. */
  volatility: number;
  sourceSystem: string;
  /**
   * Describes the work sitting behind the gap. `{count}` is the affected
   * volume, `{total}` the denominator, `{gap}` the shortfall vs target.
   */
  gapTemplate: string;
  /** Driver volume used to size `{count}` / `{total}`. */
  volumeKey?: string;
  /** Share of driver volume that is "affected" when the KPI misses. */
  affectedShareKey?: string;
  unitNoun?: string;
  /** The sub-service this indicator belongs to. */
  subServiceId?: string;
  /** Headline KPI for the service card / roll-ups. */
  primary?: boolean;
}

