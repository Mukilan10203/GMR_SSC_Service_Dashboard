import type { BotStatus, ServiceId } from "../domain/types";

/**
 * The digital workforce roster.
 *
 * Automation is not a separately contracted tower — it is delivered *inside*
 * the five service towers. Every bot therefore belongs to a service, and it
 * is not given an absolute volume: it is given a `share` of the transaction
 * volume that service's `<service>-bottxn` rate-card line has already billed
 * for. The engine distributes each service's billed bot volume across
 * whichever of its bots are licensed for the entity, so the control tower
 * always adds up to the invoice. Hours saved and cost savings fall out of the
 * same distribution.
 *
 * Each service must have at least as many bots here as its
 * `<service>-botlic` licence line bills for at full scale.
 */

export interface BotSpec {
  key: string;
  name: string;
  kind: "RPA Bot" | "AI Agent";
  process: string;
  serviceId: ServiceId;
  /** Sub-service the bot works inside, for the control tower breakdown. */
  subServiceId: string;
  /** Relative share of that service's automated transaction volume. */
  share: number;
  successRate: number;
  /** Manual minutes released per transaction executed. */
  minutesSavedPerTxn: number;
  /** Transactions handled per scheduled job run. */
  itemsPerJob: number;
  status: BotStatus;
  avgRuntimeMin: number;
  /** Hours before the reporting cut-off that the bot last ran. */
  lastRunHoursAgo: number;
  owner: string;
}

