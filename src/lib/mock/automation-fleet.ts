import type { BotStatus, ServiceId } from "../domain/types";

/**
 * The digital workforce roster.
 *
 * Bots are not given absolute volumes — they are given a `share` of the
 * transaction volume the Automation rate card has already billed for. The
 * engine distributes the billed `auto-txn` volume across whichever bots are
 * in scope for the entity, so the control tower always adds up to the
 * invoice. Hours saved and cost savings fall out of the same distribution.
 */

export interface BotSpec {
  key: string;
  name: string;
  kind: "RPA Bot" | "AI Agent";
  process: string;
  serviceId: ServiceId;
  /** Relative share of automated transaction volume. */
  share: number;
  successRate: number;
  /** Manual minutes released per transaction executed. */
  minutesSavedPerTxn: number;
  /** Transactions handled per scheduled job run. */
  itemsPerJob: number;
  status: BotStatus;
  avgRuntimeMin: number;
  /** Hours before the reporting cut-off that the bot last ran. */
  lastRunHoursAgo: number;
  owner: string;
}

